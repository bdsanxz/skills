// Build scripts/template.js from src/: one file that runs with Bun and needs nothing else.
// Run: bun run build (in dev/template-cli)

import fs from "node:fs";
import path from "node:path";

const outfile = path.resolve(import.meta.dir, "..", "..", "scripts", "template.js");
const result = await Bun.build({
  entrypoints: [path.join(import.meta.dir, "src", "main.ts")],
  target: "bun",
  format: "esm",
  minify: false,
});
if (!result.success) {
  for (const message of result.logs) console.error(message);
  process.exit(1);
}
const banner =
  "#!/usr/bin/env bun\n" +
  "// Built from dev/template-cli/src by dev/template-cli/build.ts. Do not edit this file; edit the source and build again.\n";
const code = (await result.outputs[0]!.text()).replace(/^#!.*\n/, "");
fs.mkdirSync(path.dirname(outfile), { recursive: true });
fs.writeFileSync(outfile, banner + code);
fs.chmodSync(outfile, 0o755);
console.log(`Built ${outfile} (${fs.statSync(outfile).size} bytes)`);
