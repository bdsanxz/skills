// Build scripts/pi-roster.js from index.ts+logic.ts: one file pi loads with -e.
// Run: bun run build (in dev/pi-roster)

import fs from "node:fs";
import path from "node:path";

const outfile = path.resolve(import.meta.dir, "..", "..", "scripts", "pi-roster.js");
const result = await Bun.build({
  entrypoints: [path.join(import.meta.dir, "index.ts")],
  target: "node",
  format: "esm",
  minify: false,
});
if (!result.success) {
  for (const message of result.logs) console.error(message);
  process.exit(1);
}
const banner =
  "// Built from dev/pi-roster by dev/pi-roster/build.ts. Do not edit this file; edit the source and build again.\n";
const code = (await result.outputs[0]!.text()).replace(/^#!.*\n/, "");
fs.writeFileSync(outfile, banner + code);
console.log(`Built ${outfile} (${fs.statSync(outfile).size} bytes)`);
