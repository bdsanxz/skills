export const MARKER = "<!-- generated by agent-roster-design";
const NAME_RE = /^[a-z][a-z0-9-]{0,31}$/;

/** roster.json as read; structureProblems() checks its shape before anything relies on it. */
export type Roster = JsonObject;
export type Overrides = { agent: Map<string, string>; model: Map<string, string>; effort: Map<string, string> };

export function noOverrides(): Overrides {
  return { agent: new Map(), model: new Map(), effort: new Map() };
}

export function loadRoster(workspace: string): Roster {
  const file = join(workspace, "roster.json");
  if (!isFile(file)) fail(`${file} does not exist; write the roster first`);
  return parseJsonFile(file, "fix it, then run the command again") as Roster;
}

function defaultsOf(roster: Roster): JsonObject {
  return isObject(roster.defaults) ? roster.defaults : {};
}

/** Each member with its effective "agent", "model" and "effort", and where each came from. */
export function resolve(roster: Roster, overrides: Overrides): Member[] {
  const defaults = defaultsOf(roster);
  const models = isObject(defaults.models) ? defaults.models : {};
  return (roster.members as JsonObject[]).map((raw) => {
    const m = raw as JsonObject & { name: string };
    const own = (truthy(m.agent) ? m.agent : truthy(defaults.agent) ? defaults.agent : DEFAULT_AGENT) as string;
    const e = { ...m } as unknown as Member;
    e.agent_from = truthy(m.agent) ? "member" : truthy(defaults.agent) ? "defaults.agent" : "built-in default";
    e.agent = overrides.agent.get(m.name) ?? own;
    if (overrides.agent.has(m.name)) e.agent_from = "--agent";
    const defaultModel = models[e.agent];
    const memberModel = truthy(m.model) ? (m.model as string) : null;
    if (overrides.model.has(m.name)) [e.model, e.model_from] = [overrides.model.get(m.name)!, "--model"];
    else if (memberModel && e.agent === own) [e.model, e.model_from] = [strip(memberModel), "member"];
    else if (truthy(defaultModel)) [e.model, e.model_from] = [strip(defaultModel as string), `defaults.models.${e.agent}`];
    else [e.model, e.model_from] = [null, "none set"];
    e.dropped_model = memberModel && e.agent !== own ? memberModel : null;
    if (overrides.effort.has(m.name)) [e.effort, e.effort_from] = [overrides.effort.get(m.name)!, "--effort"];
    else if (truthy(m.effort)) [e.effort, e.effort_from] = [m.effort as string, "member"];
    else if (truthy(defaults.effort)) [e.effort, e.effort_from] = [defaults.effort as string, "defaults.effort"];
    else [e.effort, e.effort_from] = [null, "none set"];
    e.ignored = [];
    if (!(AGENTS[e.agent]?.launchSettings ?? true)) {
      // The agent takes no model or effort at launch. A value meant for it is reported;
      // defaults.effort is meant for the whole squad, so it just does not apply.
      if (e.model && e.model_from !== "defaults.effort") e.ignored.push(`model ${repr(e.model)} (${e.model_from})`);
      if (e.effort && e.effort_from !== "defaults.effort") e.ignored.push(`effort ${repr(e.effort)} (${e.effort_from})`);
      [e.model, e.model_from, e.effort, e.effort_from] = [null, "managed by the agent", null, "managed by the agent"];
      e.dropped_model = null;
    }
    return e;
  });
}

export function describe(e: Member) {
  const spec = agent(e.agent);
  if (!spec.launchSettings) return `agent ${e.agent} (${e.agent_from}), model and effort managed by ${spec.label}`;
  const model = e.model ? `model ${e.model} (${e.model_from})` : "the agent's own default model (no model set)";
  const effort = e.effort ? `effort ${e.effort} (${e.effort_from})` : "the agent's own default effort (no effort set)";
  return `agent ${e.agent} (${e.agent_from}), ${model}, ${effort}`;
}

function isPlainCwd(cwd: unknown): cwd is string {
  if (!isText(cwd) || !cwd || cwd.startsWith("/") || cwd.split("/").includes("..")) return false;
  return !cwd.replace(/^\/+|\/+$/g, "").includes("/");
}

export function structureProblems(roster: Json, overrides: Overrides) {
  const problems: string[] = [];
  if (!isObject(roster)) return ['roster.json must be an object with "squad", "goal" and "members"'];
  for (const key of ["squad", "goal"]) {
    if (!isFilled(roster[key])) problems.push(`roster.json: "${key}" must be a non-empty string`);
  }
  const agents = Object.keys(AGENTS).join(", ");
  const levels = LEVELS.join(", ");
  const defaults = "defaults" in roster ? roster.defaults : {};
  if (!isObject(defaults) || Object.keys(defaults).some((key) => !["agent", "models", "effort"].includes(key))) {
    problems.push('roster.json: "defaults" must be an object with "agent", "models" and/or "effort"');
  } else {
    if ("effort" in defaults && !isLevel(defaults.effort)) {
      problems.push(`roster.json: defaults.effort ${repr(defaults.effort)} is not an effort level; use one of ${levels}`);
    }
    if ("agent" in defaults && !isAgent(defaults.agent)) {
      problems.push(`roster.json: defaults.agent ${repr(defaults.agent)} is not an agent; use one of ${agents}`);
    }
    const models = "models" in defaults ? defaults.models : {};
    if (!isObject(models)) {
      problems.push("roster.json: defaults.models must map an agent to its default model");
    } else {
      for (const [name, model] of Object.entries(models)) {
        if (!isAgent(name)) {
          problems.push(`roster.json: defaults.models names ${repr(name)}, which is not an agent; use ${agents}`);
        } else if (!isFilled(model)) {
          problems.push(`roster.json: defaults.models.${name} must be a model name, ${agent(name).modelHint}`);
        }
      }
    }
  }
  const members = roster.members;
  if (!Array.isArray(members) || !members.length) return [...problems, 'roster.json: "members" must be a non-empty list'];
  const names = new Set<string>();
  const cwds = new Set<string>();
  const shownNames = new Set<string>();
  members.forEach((m, i) => {
    let where = `members[${i}]`;
    if (!isObject(m)) {
      problems.push(`${where} must be an object`);
      return;
    }
    const name = m.name;
    if (!isText(name) || !NAME_RE.test(name)) {
      problems.push(`${where}: "name" must be kebab-case, 1-32 characters, starting with a letter`);
    } else if (names.has(name)) {
      problems.push(`${where}: name ${repr(name)} is used twice`);
    } else {
      names.add(name);
      where = `member ${repr(name)}`;
    }
    if ("runtime" in m) {
      if ("agent" in m) problems.push(`${where}: has both "agent" and the older "runtime"; keep only "agent"`);
      else m.agent = isText(m.runtime) ? (LEGACY_AGENTS[m.runtime] ?? m.runtime) : m.runtime;
    }
    if ("agent" in m && !isAgent(m.agent)) {
      problems.push(
        `${where}: "agent" ${repr(m.agent)} is not an agent; use one of ${agents}, or leave it out to use the default`,
      );
    }
    if (!isFilled(m.summary)) problems.push(`${where}: "summary" must be a one-line description of the role`);
    if ("display_name" in m) {
      const given = m.display_name;
      if (!isFilled(given) || length(strip(given)) > 48 || /[\n\r|`]/.test(given)) {
        problems.push(
          `${where}: "display_name" must be a human-readable name of 1-48 characters ` +
            'on one line, without | or ` and without the role, such as "Rina"; or leave it out',
        );
      } else if (shownNames.has(strip(given).toLowerCase())) {
        problems.push(`${where}: display_name ${repr(strip(given))} is used by another member`);
      } else {
        shownNames.add(strip(given).toLowerCase());
      }
    }
    // The model's form depends on the agent, so modelProblems checks it.
    if ("model" in m && !isFilled(m.model)) {
      problems.push(`${where}: "model" must be one model name for its agent, such as "haiku" for claude`);
    }
    if ("effort" in m && !isLevel(m.effort)) {
      problems.push(
        `${where}: "effort" ${repr(m.effort)} is not an effort level; use one of ${levels}, or leave it out to use the default`,
      );
    }
    // The runtime session launch records, so rebuild and launch know which session is
    // the member's. peers send/open never read it: they address members by herdr name.
    if ("session" in m) {
      if (!validSession(m.session)) {
        problems.push(
          `${where}: "session" must be {"runtime": <agent>, "id": <session id>}, as launch records it; or leave it out`,
        );
      } else if (!isAgent(m.session.runtime)) {
        problems.push(`${where}: "session".runtime ${repr(m.session.runtime)} is not an agent; use one of ${agents}`);
      }
    }
    const cwd = m.cwd;
    if (!isPlainCwd(cwd)) problems.push(`${where}: "cwd" must be one directory name inside the workspace`);
    else if (cwds.has(cwd)) problems.push(`${where}: cwd ${repr(cwd)} is used by another member`);
    else cwds.add(cwd);
    if ("talks_to" in m && !(Array.isArray(m.talks_to) && m.talks_to.every(isText))) {
      problems.push(`${where}: "talks_to" must be a list of member names`);
    }
    if (!isText(m.reports_to)) problems.push(`${where}: "reports_to" must be a member name or "user"`);
    const skills = "skills" in m ? m.skills : [];
    (Array.isArray(skills) ? skills : [null]).forEach((skill, j) => {
      if (!(isObject(skill) && isFilled(skill.source) && isFilled(skill.skill))) {
        problems.push(`${where}: skills[${j}] must be {"source": <package, URL or path>, "skill": <name>}`);
      } else if (skill.skill === "peers") {
        problems.push(`${where}: skills[${j}] lists peers, which every member gets; set "peers_source" instead`);
      } else if (skill.skill === "agent-job") {
        problems.push(`${where}: skills[${j}] lists agent-job, which every member gets; set "agent_job_source" instead`);
      } else if (skill.skill === "agent-shell") {
        problems.push(`${where}: skills[${j}] lists agent-shell, which every member gets; set "agent_shell_source" instead`);
      }
    });
  });
  if ("peers_source" in roster && !isFilled(roster.peers_source)) {
    problems.push('roster.json: "peers_source" must be a package, URL or path of the peers skill');
  }
  if ("agent_job_source" in roster && !isFilled(roster.agent_job_source)) {
    problems.push('roster.json: "agent_job_source" must be a package, URL or path of the agent-job skill');
  }
  if ("agent_shell_source" in roster && !isFilled(roster.agent_shell_source)) {
    problems.push('roster.json: "agent_shell_source" must be a package, URL or path of the agent-shell skill');
  }
  for (const flag of ["agent", "model", "effort"] as const) {
    for (const [name, value] of overrides[flag]) {
      if (!names.has(name)) problems.push(`--${flag} ${name}=${value}: no member named ${repr(name)} in roster.json`);
      else if (flag === "agent" && !isAgent(value)) {
        problems.push(`--agent ${name}=${value}: ${repr(value)} is not an agent; use one of ${agents}`);
      } else if (flag === "effort" && !isLevel(value)) {
        problems.push(`--effort ${name}=${value}: ${repr(value)} is not an effort level; use one of ${levels}`);
      }
    }
  }
  return problems;
}

/** Problems and notes about each member's agent, model and effort, for its effective agent.
 * A default effort the member cannot use is moved to its nearest level here, with a note. */
export function modelProblems(members: Member[], strict: boolean): [string[], string[]] {
  const problems: string[] = [];
  const notes: string[] = [];
  for (const e of members) {
    const where = `member ${repr(e.name)}`;
    const spec = agent(e.agent);
    if (e.ignored.length) {
      notes.push(
        `WARNING ${where}: ignored ${e.ignored.join(" and ")}; ${e.agent} is launched without them. ${spec.settingsNote}.`,
      );
    }
    if (e.dropped_model) {
      notes.push(
        `${where}: its model ${repr(e.dropped_model)} is for its roster agent, so with agent ` +
          `${e.agent} it uses ${e.model || "the agent's own default model"}`,
      );
    }
    if (strict && !which(spec.command)) {
      problems.push(`${where}: agent ${e.agent} needs the \`${spec.command}\` command, which is not on PATH`);
    }
    if (e.model) {
      if (!spec.modelPattern.test(e.model)) {
        problems.push(
          `${where}: model ${repr(e.model)} (${e.model_from}) is not a ${e.agent} model; expected ${spec.modelHint}`,
        );
        continue;
      }
      let [ids, why] = availableModels(e.agent);
      if (e.agent === "agy" && ids) {
        // A base name such as gemini-3.8-flash takes its level from --effort.
        const bases = [...ids].filter((id) => isLevel(rpartition(id, "-")[2])).map((id) => rpartition(id, "-")[0]);
        ids = new Set([...ids, ...bases]);
      }
      if (ids && !ids.has(e.model)) {
        problems.push(
          `${where}: model ${repr(e.model)} (${e.model_from}) is not available to ${e.agent}; ` +
            `\`${spec.listModels!.join(" ")}\` lists: ${[...ids].sort().join(", ")}`,
        );
        continue;
      }
      if (why) (strict ? problems : notes).push(`${where}: cannot confirm model ${repr(e.model)}: ${why}`);
    }
    if (!e.effort) continue;
    const [supported, why] = effortLevels(e);
    const model = e.model || `${e.agent}'s default model`;
    if (!supported) {
      if (e.effort_from === "defaults.effort") {
        notes.push(
          `${where}: defaults.effort ${repr(e.effort)} does not apply: ${why}; it uses the agent's own default effort`,
        );
        [e.effort, e.effort_from] = [null, "defaults.effort, not applicable"];
      } else if (!e.model) {
        problems.push(`${where}: effort ${repr(e.effort)} (${e.effort_from}): ${why}`);
      } else {
        (strict ? problems : notes).push(`${where}: cannot confirm effort ${repr(e.effort)}: ${why}`);
      }
    } else if (!supported.has(e.effort)) {
      const listed = LEVELS.filter((level) => supported.has(level)).join(", ");
      const have = listed ? `it has ${listed}` : "it has no effort levels";
      if (e.effort_from === "defaults.effort") {
        const level = supported.size ? nearest(e.effort, supported) : null;
        notes.push(
          `${where}: ${model} has no ${repr(e.effort)} effort (${have}), so it uses ` +
            (level ? `the nearest, ${repr(level)}` : "the agent's own default effort"),
        );
        [e.effort, e.effort_from] = [level, level ? "nearest to defaults.effort" : "defaults.effort, not supported"];
      } else {
        let hint = supported.size ? `; the nearest it has is ${repr(nearest(e.effort, supported))}` : "";
        const base = e.agent === "agy" && e.model ? rpartition(e.model, "-")[0] : "";
        if (base && supported.size === 1 && effortLevels({ agent: e.agent, model: base })[0]?.has(e.effort)) {
          hint += `; or set the model to ${repr(base)}, which takes its level from the effort`;
        }
        problems.push(
          `${where}: effort ${repr(e.effort)} (${e.effort_from}) is not supported by ${e.agent} with ${model}; ${have}${hint}`,
        );
      }
    }
  }
  return [problems, notes];
}

/** The file's text without a leading `# <title>` heading. */
export function body(content: string, title: string) {
  const lines = strip(content).split(/\r\n|[\n\r\x0b\x0c\x1c\x1d\x1e\x85\u2028\u2029]/);
  if (lines.length && new RegExp(`^#\\s+${escapeRegExp(title)}\\s*$`, "i").test(lines[0]!)) lines.shift();
  return strip(lines.join("\n"));
}

/** [problems, notes, effective members]. strict is for launch: every agent's CLI must be there. */
export function rosterProblems(
  workspace: string,
  roster: Json,
  overrides: Overrides = noOverrides(),
  strict = false,
): [string[], string[], Member[] | null] {
  const problems = structureProblems(roster, overrides);
  if (problems.length) return [problems, [], null];
  const members = resolve(roster as Roster, overrides);
  const names = new Set(members.map((m) => m.name));
  for (const m of members) {
    const where = `member ${repr(m.name)}`;
    if (m.reports_to !== "user" && !names.has(m.reports_to)) {
      problems.push(`${where}: reports_to ${repr(m.reports_to)} is not a member or "user"`);
    }
    if (m.reports_to === m.name) problems.push(`${where}: reports to itself`);
    for (const other of m.talks_to ?? []) {
      if (!names.has(other)) problems.push(`${where}: talks_to ${repr(other)} is not a member`);
      else if (other === m.name) problems.push(`${where}: talks_to names itself`);
    }
  }
  if (!members.some((m) => m.reports_to === "user")) {
    problems.push('no member reports to "user": someone must report the squad\'s results out');
  }
  // A report chain that loops never reaches the user.
  const boss = new Map(members.map((m) => [m.name, m.reports_to]));
  for (const name of boss.keys()) {
    const seen = new Set<string>();
    let current = name;
    while (boss.has(current) && !seen.has(current)) {
      seen.add(current);
      current = boss.get(current)!;
    }
    if (boss.has(current)) {
      problems.push(
        `member ${repr(name)}: its report chain loops (${[...seen].sort().join(" -> ")}) and never reaches "user"`,
      );
      break;
    }
  }
  if (!problems.length) {
    // The layout follows the report chains, so it is checked once they are sound.
    problems.push(...layoutProblems(planLayout(members), members).map((problem) => `layout: ${problem}`));
  }
  const [agentProblems, notes] = modelProblems(members, strict);
  problems.push(...agentProblems);
  for (const m of members) {
    // A malformed session is already a problem above; only a sound one is checked here.
    if (!validSession(m.session) || !isAgent(m.session.runtime)) continue;
    const where = `member ${repr(m.name)}`;
    if (m.session.runtime !== m.agent) {
      notes.push(
        `${where}: session records runtime ${repr(m.session.runtime)} but the member runs on ${repr(m.agent)}; ` +
          "launch records a fresh session when it starts",
      );
    } else if (sessionLive(m.session.runtime, m.session.id) === false) {
      notes.push(
        `${where}: session ${m.session.runtime}:${m.session.id} is not live; ` +
          `relaunch it with \`bun ${SCRIPT} launch ${workspace} --member ${m.name}\``,
      );
    }
  }
  for (const m of members) {
    const dir = join(workspace, m.cwd);
    for (const [name, title] of PARTS) {
      const file = join(dir, name);
      if (!isFile(file)) problems.push(`member ${repr(m.name)}: ${file} is missing`);
      // MEMORY.md starts with no entries.
      else if (name !== "MEMORY.md" && !body(readText(file), title)) problems.push(`member ${repr(m.name)}: ${file} is empty`);
    }
    const comms = join(dir, "COMMUNICATIONS.md");
    if (isFile(comms)) {
      const content = readText(comms);
      const linked = new Set([...(m.talks_to ?? []), ...(m.reports_to !== "user" ? [m.reports_to] : [])]);
      for (const other of [...linked].sort()) {
        if (!new RegExp(`(?<![a-z0-9-])${escapeRegExp(other)}(?![a-z0-9-])`).test(content)) {
          problems.push(
            `member ${repr(m.name)}: COMMUNICATIONS.md never names ${repr(other)}, whom roster.json says it talks or reports to`,
          );
        }
      }
    }
    const target = join(dir, agent(m.agent).instructions);
    if (isFile(target) && !readText(target).includes(MARKER)) {
      problems.push(
        `member ${repr(m.name)}: ${target} exists and was not generated by this script; ` +
          "move its content into the member's files, then delete it",
      );
    }
  }
  return [problems, notes, members];
}

/** The member's instruction file: who it is, references to its four files (never their content:
 * each file stays the one source of truth), and the squad directory. */
export function assemble(workspace: string, roster: Roster, members: Member[], m: Member) {
  const dir = join(workspace, m.cwd);
  const named = truthy(m.display_name);
  const anyNamed = members.some((o) => truthy(o.display_name));
  const rebuild = `bun ${SCRIPT} assemble ${workspace} --member ${m.name}`;
  const lines = [
    `${MARKER}: do not edit this file. Your instructions are in the files it references; edit those. ` +
      `After roster.json changes, regenerate this file with: ${rebuild} -->`,
    "",
    named
      ? `# ${display(m)} (\`${m.name}\`): member of the ${roster.squad} squad`
      : `# ${m.name}: member of the ${roster.squad} squad`,
    "",
    `Squad goal: ${strip(roster.goal as string)}`,
    "",
    (named ? `You are ${display(m)}, the member \`${m.name}\`.` : `You are \`${m.name}\`.`) +
      ` You work in \`${dir}\`. Other members are separate agent sessions; ` +
      "you reach them only through the peers skill (`peers`).",
    "",
    "## Your instructions",
    "",
  ];
  if (agent(m.agent).imports) {
    // Claude Code loads @-imports itself, from the files' own paths.
    lines.push(
      "These files are your instructions, and the only place they are kept; they load with this file. " +
        "Follow them as if they were written here.",
      "",
      ...PARTS.map(([name, title]) => `- ${title}: @${join(dir, name)}`),
    );
  } else {
    lines.push(
      "These files are your instructions, and the only place they are kept. Read all four, in this order, " +
        "at the start of every session, before you answer the first message or do anything else, and follow " +
        "them as if they were written here. Read a file again whenever someone tells you it changed.",
      "",
      ...PARTS.map(([name, title]) => `- ${title}: \`${join(dir, name)}\``),
    );
  }
  lines.push(
    "",
    "When you are corrected, or asked to behave in a particular way from now on, add the lesson to " +
      `\`${join(dir, "MEMORY.md")}\` as one short entry. Never record lessons in this file.`,
  );
  if (m.agent === "pi" || m.agent === "opencode") {
    lines.push(
      "",
      "## Loop",
      "",
      "You have a `/loop` command for repeated work: `/loop 5m <prompt>` runs the prompt now and repeats it every 5 minutes, " +
        "`/loop <prompt>` runs it now and wakes again when the Schedule tool says, and `/loop stop` ends the loop. " +
        "After a dynamic iteration, call the Schedule tool with the delay, a short reason, and noop true when nothing changed.",
    );
  }
  if (anyNamed) {
    lines.push(
      "",
      "Each member has a member name (in backticks below), which `roster.json`, `reports_to`, " +
        "`talks_to` and peers use as its role, and a human-readable name, which peers shows with the " +
        "role, as in `Rina (api)`. Call members by their human-readable name when you write to or " +
        "about them; use the member name wherever a file or command asks for one.",
    );
  }
  lines.push(
    "",
    "## Squad directory",
    "",
    "Find a member's address with `peers contacts`, which lists every member that has used peers " +
      "in this squad, or with `peers list`, picking the row whose cwd is the member's " +
      "directory below. Addresses change when a member is restarted, even on another agent; " +
      "look them up again rather than reusing an old one. In `peers contacts`, use the member's " +
      "`status=live` row; never message a `status=replaced` row, whose member now runs at its `by=` address.",
    "",
    "| Member |" + (anyNamed ? " Name |" : "") + " Agent | Model | Effort | Role | Directory | Reports to |",
    "| --- |" + (anyNamed ? " --- |" : "") + " --- | --- | --- | --- | --- | --- |",
  );
  for (const o of members) {
    const me = o.name === m.name ? " (you)" : "";
    const spec = agent(o.agent);
    const fallback = spec.launchSettings ? "agent default" : `set in ${spec.label}`;
    lines.push(
      `| \`${o.name}\`${me} |` +
        (anyNamed ? ` ${display(o)} |` : "") +
        ` ${o.agent} | ${o.model || fallback} | ` +
        `${o.effort || fallback} | ${strip(o.summary)} | ` +
        `\`${join(workspace, o.cwd)}\` | ${o.reports_to} |`,
    );
  }
  return lines.join("\n") + "\n";
}

/** Install peers, agent-job, agent-shell and the member's other skills into its cwd, for its agent. */
export function installSkills(dir: string, m: Member, sources: SkillSources) {
  const spec = agent(m.agent);
  const wanted: [string, string][] = [[sources.peers, "peers"], [sources.agentJob, "agent-job"], [sources.agentShell, "agent-shell"], ...(m.skills ?? []).map((s): [string, string] => [s.source, s.skill])];
  const bySource = new Map<string, string[]>();
  for (const [source, skill] of wanted) {
    if (!bySource.has(source)) bySource.set(source, []);
    bySource.get(source)!.push(skill);
  }
  const installed: string[] = [];
  for (const [source, skills] of bySource) {
    const cmd = ["npx", "-y", "skills@latest", "add", source, "-a", spec.skillsCli, "-y", "--copy"];
    for (const skill of skills) cmd.push("--skill", skill);
    const done = run(cmd, { cwd: dir });
    if (done.code !== 0) {
      const log = tail(strip((done.stderr + done.stdout).replace(/\x1b\[[0-9;?]*[A-Za-z]/g, "")), 1500);
      fail(
        `installing ${skills.join(", ")} from ${source} for member ${repr(m.name)} failed ` +
          `(exit ${done.code}): ${cmd.join(" ")}\n${log}`,
      );
    }
    for (const skill of skills) {
      if (!isFile(join(dir, spec.skillsDir, skill, "SKILL.md"))) {
        fail(
          `\`${cmd.join(" ")}\` in ${dir} did not install ${repr(skill)} into ${spec.skillsDir}; ` +
            "check that the source has a skill by that name with valid SKILL.md frontmatter " +
            `(\`npx -y skills@latest add ${source} --list\`)`,
        );
      }
      installed.push(skill);
    }
  }
  return installed;
}

export function writeInstructions(workspace: string, roster: Roster, members: Member[], m: Member) {
  const dir = join(workspace, m.cwd);
  const target = join(dir, agent(m.agent).instructions);
  fs.writeFileSync(target + ".tmp", assemble(workspace, roster, members, m));
  fs.renameSync(target + ".tmp", target);
  for (const name of new Set(Object.values(AGENTS).map((spec) => spec.instructions))) {
    // Left from an earlier agent.
    const stale = join(dir, name);
    if (stale !== target && isFile(stale) && readText(stale).includes(MARKER)) fs.rmSync(stale);
  }
  return target;
}

export function identityPath(workspace: string, m: Member) {
  return join(workspace, m.cwd, ".peers.json");
}

export function writeIdentity(workspace: string, roster: Roster, m: Member) {
  // peers reads the sender's role and display_name from the nearest .peers.json and stores
  // them with every message;
  // launch compares the agent, model and effort recorded here with the ones it is asked to start.
  const file = identityPath(workspace, m);
  mergeJson(file, (data) => {
    Object.assign(data, { role: m.name, squad: roster.squad as string, agent: m.agent });
    for (const key of ["display_name", "model", "effort"] as const) {
      const value = m[key];
      if (truthy(value)) data[key] = strip(value as string);
      else delete data[key];
    }
  });
  return file;
}

export function buildMember(workspace: string, roster: Roster, members: Member[], m: Member, sources: SkillSources) {
  const dir = join(workspace, m.cwd);
  const done = [
    `wrote ${writeInstructions(workspace, roster, members, m)}`,
    `wrote ${writeIdentity(workspace, roster, m)}`,
  ];
  const skills = installSkills(dir, m, sources);
  done.push(`installed ${skills.join(", ")} in ${join(dir, agent(m.agent).skillsDir)}`);
  const configured = agent(m.agent).configure(workspace, dir, m);
  if (configured) done.push(configured);
  return done;
}

export function selected(members: Member[], name: string | null) {
  if (!name) return members;
  const found = members.filter((m) => m.name === name);
  if (!found.length) {
    const names = members.map((m) => m.name).join(", ");
    fail(`no member named ${repr(name)} in roster.json; its members are ${names}`);
  }
  return found;
}
