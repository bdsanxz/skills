// Build scripts/peers-pi.js from src/: one pi extension file that needs only Node's built-ins.
// Run: bun run build (in dev/peers-pi)

import fs from "node:fs";
import path from "node:path";

const outfile = path.resolve(import.meta.dir, "..", "..", "scripts", "peers-pi.js");
const result = await Bun.build({
  entrypoints: [path.join(import.meta.dir, "src", "index.ts")],
  target: "node",
  format: "esm",
  minify: false,
});
if (!result.success) {
  for (const message of result.logs) console.error(message);
  process.exit(1);
}
const banner =
  "// peers: delivers peer notifications into a pi session as user turns. Load it with\n" +
  "// `pi -e <path to this file>`, or copy it to ~/.pi/agent/extensions/ for every session.\n" +
  "// Built from dev/peers-pi/src by dev/peers-pi/build.ts. Do not edit this file; edit the source and build again.\n";
fs.mkdirSync(path.dirname(outfile), { recursive: true });
fs.writeFileSync(outfile, banner + (await result.outputs[0]!.text()));
console.log(`Built ${outfile} (${fs.statSync(outfile).size} bytes)`);
